const dicts = { he, en };
let lang = 'he';

export function setLanguage(l) {
  lang = dicts[l] ? l : 'he';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
}

export const getLanguage = () => lang;

/** True if `key` is a translated string (not a raw message). */
export const hasKey = (key) => key in dicts[lang] || key in dicts.en;

export function t(key, ...args) {
  const s = dicts[lang][key] ?? dicts.en[key] ?? key;
  return s.replace(/\{(\d)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}

/** Fills elements carrying data-i18n / data-i18n-title / data-i18n-placeholder. */
export function translateDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
}
